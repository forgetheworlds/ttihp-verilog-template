; PROTEUS firmware -- 10BASE-T MII transmit, pure firmware, engines 0 and 1
; =============================================================================
; CAN PROTEUS DRIVE AN ETHERNET PHY?  Two answers, both measured:
;
;   MII nibble stream, 10 Mbit/s      YES, in 32 words (engine 0 below).
;   Complete 802.3 frame incl. FCS    NO.  The frame emitter alone needs 230
;                                     words against a 32-word engine, and the
;                                     FCS needs its own 32-word engine.  The
;                                     exact counts are in "Budget".
;
; Two programs, both inside the 32-word default build, both verified:
;
;   engine 0  32/32  MII nibble transmitter: preamble + SFD + frame body,
;                    clocked by the PHY's TX_CLK, TX_EN gating, IFG, halt.
;   engine 1  32/32  Ethernet FCS: reflected CRC-32 (poly 0xEDB88320, init
;                    0xFFFFFFFF, final XOR 0xFFFFFFFF, LSB first) over a frame
;                    the host relays through IN_FIFO.
;
; They cannot be one program (see "Budget"), and they cannot run concurrently
; on one frame either: engine 1 needs 140.8 cycles per byte while the wire
; grants 40 cycles per byte at 10 Mbit/s.  The FCS is a pre-transmit
; computation (169 us for the 60-byte frame, i.e. once per frame at boot or
; during an arbitrarily long IFG), not an inline one.
;
; Implemented and verified (demos/run_eth.py, PASS):
;   * TX_CLK-paced nibble output, 108 nibbles, TX_EN high for every one of
;     them and for no other rising edge, TXD/TX_EN setup >= 4 cycles (80 ns)
;     and hold >= 12 cycles (240 ns) around every sampling edge.
;   * preamble exactly 7 x 0x55, SFD exactly 0xD5, byte order LSB-nibble
;     first, payload 0x00..0x2D decoded back byte for byte.
;   * 24 idle nibble times (96 bit times, the 802.3 IFG) with TX_EN = TXD = 0,
;     then HALT holds the pins; no pad contention, no collision.
;   * FCS bit-exact against zlib.crc32 on three different frames.
;
; Not implemented (honest gaps, all measured -- see results/ethernet.md):
;   * dst/src MAC and ethertype bytes on the wire: +154 words, does not fit.
;   * the FCS nibbles on the wire: +44 words in the emitter, does not fit.
;   * no RX path (RXD/RX_DV/RX_CLK are not driven or sampled), no MDIO/MDC,
;     no Manchester encoding, no carrier sense / collision detect / jam.
;     This is an MII MAC transmit path to an external PHY; the PHY, the
;     transformer and the wire are off-chip.
;   * the FCS engine covers 1..255-byte frames only (8-bit length register);
;     a 1518-byte frame needs a 16-bit counter.
;
; ---------------------------------------------------------------------------
; Pin map (MII, 6 pads, all on uio so the demo coexists with the host SPI)
;   TX_CLK  UIO[0]  input, 2.5 MHz, generated by the PHY (20 clk = one nibble)
;   TX_EN   UIO[1]  output, side-set driven: asserted for every nibble of the
;                   frame including every low phase, deasserted in the IFG
;   TXD0    UIO[2]  output  \
;   TXD1    UIO[3]  output   > nibble, LSB first; one OUTP mask 0x3C drives
;   TXD2    UIO[4]  output   > all four from bits [5:2] of a register
;   TXD3    UIO[5]  output  /
;   uio[7:6], ui_in and uo_out untouched; host SPI pins untouched.
; ---------------------------------------------------------------------------
; Engine 0: MII nibble timing (50 MHz clk, 20 cycles per nibble)
;   CFG SIDE = 0xC4 -> side-set on, bank UIO, base 1, width 1 (TX_EN).  Side-set
;   is re-driven on every cycle an instruction is in flight, stall cycles
;   included, so TX_EN never dips between nibbles and costs no slot.  Every
;   instruction inside the frame carries [ss=1]; the alignment wait, the IFG
;   park and the halt carry no side-set and therefore drive TX_EN = 0.
;
;   Per nibble: OUTP drives TXD while TX_CLK is low, then WAITP on the rising
;   edge (where the PHY latches), then WAITP on the next low phase.  A write
;   issued in cycle c appears on the pads in cycle c+1, so at 10 low / 10 high
;   cycles the nibble is stable 4..9 cycles before the edge; measured minimum
;   setup 4 cycles (80 ns), minimum hold 12 cycles (240 ns).  There is no edge
;   race: TXD only ever changes during a low phase, i.e. after the falling
;   edge and before the next rising one.
;
;   TX_CLK = 2.5 MHz is 20 cycles at 50 MHz; the model drives 10 low + 10 high.
;   Nibble order: bits [3:0] of a byte first, then bits [7:4]; within a nibble
;   TXD0 is the LSB -- the 802.3 clause 3 LSB-first order.
;
;   Frame content sent by engine 0 (108 nibbles, TX_EN high throughout):
;     7 x 0x55 preamble | 0xD5 SFD | 46 payload bytes 0x00..0x2D
;
;   Nibble generation: the payload is a counter, not memory (there is no data
;   memory).  0x14 = 5 << 2 is the pin image of nibble 5, so the preamble
;   (0x55, both nibbles 5) is one register value re-emitted 14 times.
;   ROLI r,2 puts the low nibble at bits [5:2]; RORI r,2 puts the high nibble
;   there (verified in tools/model.py), so a counter byte costs 2 words of
;   preparation per nibble instead of 3.
;
;   IFG: TX_EN and TXD are parked low, then WAITC 480 = 480 cycles = 24 TX_CLK
;   nibble times = 96 bit times, which is the 802.3 inter-frame gap and not
;   just the 12 nibbles the demo asks for.  It is a fixed 4.8 us wait, not edge
;   counting: correct while TX_CLK is the MII 2.5 MHz +-100 ppm, and it also
;   survives a PHY that stops TX_CLK while idle.  HALT then holds the pins.
;
;   Measured: 108 sampled nibbles with TX_EN = 1, 24 idle nibble times before
;   HALT, every sampled nibble equal to the expected one.
;
; ---------------------------------------------------------------------------
; Engine 1: Ethernet FCS (CRC-32)
;   r7:r4 = CRC, r4 = LSB (the byte transmitted first).  Per byte: XOR the byte
;   into r4, then 8 bit steps.  A bit step shifts the 32-bit value right by
;   one, moving bit 0 of each byte into bit 7 of the next lower byte, and XORs
;   0xEDB88320 when bit 0 of r4 was set.  The ISA has no carry-in rotate, so
;   the incoming bit travels in a mask register: MOV r3,rX; SHLI r3,7 leaves
;   only bit 0 of rX, at bit 7.  SHRI r4,1 is issued last so its carry ("was
;   odd") survives to JNC: AND/OR/XOR do not touch C (docs/isa.md §2.2).
;   The last four words apply the final XOR 0xFFFFFFFF (NOT per byte), so
;   r4..r7 hold the FCS itself, in transmit order.
;
;   Host contract: write r1 (engine window +0x05) = frame length, 1..255,
;   then RUN, then push the frame bytes into IN_FIFO (+0x10) one per SPI frame,
;   polling E_STATUS.in_full.  PULL blocks until each byte exists.  The FCS is
;   left in r4..r7 (+0x08..+0x0B): r4 is the first FCS byte on the wire.
;
;   Measured: 140.8 cycles per byte (17.6 per bit) = 8449 cycles = 169 us at
;   50 MHz for the 60-byte frame.  That is why this cannot be inlined: 10
;   Mbit/s allows 40 cycles per byte on the wire.
;
; ---------------------------------------------------------------------------
; Budget (measured; demos/run_eth.py assembles the per-byte block)
;   This file                                       32 + 32 = 64 words
;   Complete frame emitter in ONE engine:
;     engine 0 as shipped (preamble+SFD+payload+IFG+HALT)      32
;     + 14 header bytes (dst, src, ethertype) x 11 words       154
;     +  4 FCS bytes                          x 11 words        44
;     = 230 words against a 32-word engine (7.2x over)
;   A constant byte costs LDI (the byte) + 10 words to emit its two nibbles,
;   because there is no memory to hold the frame: measured 11 words per byte
;   (44 words for 4 bytes, 55 for 5).
;   Splitting into engines does not help: only one engine can own TXD/TX_EN,
;   and the only inter-engine path is the host FIFO (one byte per SPI frame),
;   so a second engine can produce the FCS but cannot feed the 60 frame bytes.
; =============================================================================

    .engine 0

    CFG SIDE,   0xC4           ; 0  side-set -> UIO[1] = TX_EN
    LDI r1, 0x14               ; 1  pin image of nibble 0x5 (0x55 preamble)
    LDI r3, 14                 ; 2  nibbles of preamble: 7 x 0x55
    WAITP UIO, 0x01, 0         ; 3  TX_EN still low: align to a low phase
p1:
    [ss=1] OUTP UIO, 0x3C, r1  ; 4  preamble nibble
    [ss=1] WAITP UIO, 0x01, 1  ; 5  rising edge: the PHY samples here
    [ss=1] WAITP UIO, 0x01, 0  ; 6  next low phase
    [ss=1] DJNZ r3, p1         ; 7

    [ss=1] OUTP UIO, 0x3C, r1  ; 8  SFD low nibble = 0x5
    [ss=1] WAITP UIO, 0x01, 1  ; 9
    [ss=1] WAITP UIO, 0x01, 0  ; 10
    [ss=1] LDI r1, 0x34        ; 11 pin image of nibble 0xD
    [ss=1] OUTP UIO, 0x3C, r1  ; 12 SFD high nibble = 0xD
    [ss=1] WAITP UIO, 0x01, 1  ; 13
    [ss=1] WAITP UIO, 0x01, 0  ; 14

    [ss=1] LDI r0, 0x00        ; 15 payload byte 0x00..0x2D
    [ss=1] LDI r3, 46          ; 16 payload byte count
pl:
    [ss=1] MOV r2, r0          ; 17
    [ss=1] ROLI r2, 2          ; 18 bits [5:2] = low nibble
    [ss=1] OUTP UIO, 0x3C, r2  ; 19 low nibble
    [ss=1] WAITP UIO, 0x01, 1  ; 20
    [ss=1] WAITP UIO, 0x01, 0  ; 21
    [ss=1] MOV r2, r0          ; 22
    [ss=1] RORI r2, 2          ; 23 bits [5:2] = high nibble
    [ss=1] OUTP UIO, 0x3C, r2  ; 24 high nibble
    [ss=1] WAITP UIO, 0x01, 1  ; 25
    [ss=1] WAITP UIO, 0x01, 0  ; 26
    [ss=1] INC r0              ; 27
    [ss=1] DJNZ r3, pl         ; 28

    CLRP UIO, 0x3C             ; 29 TX_EN (side-set 0) and TXD = 0
    WAITC 480                  ; 30 IFG = 480 cycles = 24 nibble times
    HALT                       ; 31 pins hold TX_EN = TXD = 0

; =============================================================================
; Ethernet FCS over r1 frame bytes (1..255), LSB first.  r4..r7 = FCS, r4 = LSB.
; =============================================================================

    .engine 1

    LDI r4, 0xFF               ; 0  CRC init = 0xFFFFFFFF
    MOV r5, r4                 ; 1
    MOV r6, r4                 ; 2
    MOV r7, r4                 ; 3
                               ;    r1 = frame length, written by the host
byte:
    PULL r0                    ; 4  next frame byte (blocks)
    XOR r4, r0                 ; 5  crc ^= byte, into the LSB byte
    LDI r2, 8                  ; 6  bits per byte
bit:
    MOV r3, r7                 ; 7  m3 = bit0(r7) << 7
    SHLI r3, 7                 ; 8
    SHRI r7, 1                 ; 9  r7 >>= 1
    MOV r0, r6                 ; 10 m2 = bit0(r6) << 7
    SHLI r0, 7                 ; 11
    SHRI r6, 1                 ; 12
    OR r6, r3                  ; 13 r6 = (r6 >> 1) | m3
    MOV r3, r5                 ; 14 m1 = bit0(r5) << 7
    SHLI r3, 7                 ; 15
    SHRI r5, 1                 ; 16
    OR r5, r0                  ; 17 r5 = (r5 >> 1) | m2
    SHRI r4, 1                 ; 18 r4 >>= 1, C = old bit0 (the CRC LSB)
    OR r4, r3                  ; 19 r4 = (r4 >> 1) | m1; OR leaves C alone
    JNC nobit                  ; 20
    XORI r4, 0x20              ; 21 poly 0xEDB88320 bytes 0..3, LSB first
    XORI r5, 0x83              ; 22
    XORI r6, 0xB8              ; 23
    XORI r7, 0xED              ; 24
nobit:
    DJNZ r2, bit               ; 25
    DJNZ r1, byte              ; 26
    NOT r4                     ; 27 final XOR 0xFFFFFFFF, byte by byte
    NOT r5                     ; 28
    NOT r6                     ; 29
    NOT r7                     ; 30
    HALT                       ; 31 FCS is in r4..r7, r4 = first byte sent
