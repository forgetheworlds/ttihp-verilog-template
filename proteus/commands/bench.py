"""``proteus bench`` -- deterministic agent benchmark from the mutation specs.

Each task is one of the single-bug mutations in ``tools/mutate.py``: the task
carries the mutated RTL file, the affected file and line, the exact text edit,
and a reference to a golden model trace.  The trace is produced by the
cycle-accurate ``tools/model.py`` running a small self-configuring firmware, so
it is independent of the mutations (which are RTL defects).

Everything written is deterministic for a given ``--seed/--tasks/--cycles``:
sorted JSON keys, compact JSONL, no timestamps, and no absolute paths.
"""

from __future__ import annotations

import hashlib
import random
import shutil

from .. import core

TASK_SCHEMA = "proteus.bench.task/1"
GOLDEN_SCHEMA = "proteus.bench.golden/1"
GOLDEN_FIRMWARE_NAME = "golden_blink.asm"
GOLDEN_TRACE_NAME = "golden.jsonl"
GOLDEN_SHA_NAME = "golden.sha256"
GOLDEN_META_NAME = "golden_meta.json"
TASKS_NAME = "tasks.jsonl"
README_NAME = "README.md"
MUTANTS_DIR = "mutants"

#: Small firmware that exercises the pacer and the UIO pin fabric.  It sets its
#: own 8.0-cycle pacing period, so the trace needs no host-side configuration
#: and is byte-identical on every run.  (``firmware/pin_blink.asm`` relies on a
#: host-written period and only toggles UIO through the pad input; this fixture
#: keeps the benchmark self-contained.)
GOLDEN_FIRMWARE = """\
; golden_blink.asm -- model-only fixture generated by `proteus bench`
; Engine 0 sets an 8-cycle pacer period and alternates UIO[0] forever.
    .engine 0
    CFG PERIOD0, 8
    CFG PERIOD1, 0
    SETP UIO, 0x01
loop:
    PACE
    CLRP UIO, 0x01
    PACE
    SETP UIO, 0x01
    JMP loop
"""

MANAGED_ENTRIES = frozenset({
    README_NAME, TASKS_NAME, GOLDEN_TRACE_NAME, GOLDEN_SHA_NAME,
    GOLDEN_META_NAME, GOLDEN_FIRMWARE_NAME, MUTANTS_DIR,
})


def register(subparsers, description: str) -> None:
    parser = subparsers.add_parser("bench", help=description, description=description)
    parser.add_argument("--out", required=True, metavar="DIR",
                        help="output directory (created if missing)")
    parser.add_argument("--tasks", type=int, default=12, metavar="N",
                        help="number of mutation tasks (default 12)")
    parser.add_argument("--seed", type=int, default=0, metavar="S",
                        help="selection seed (default 0)")
    parser.add_argument("--cycles", type=int, default=48, metavar="C",
                        help="golden trace length in cycles (default 48)")
    parser.set_defaults(func=run)


# ---------------------------------------------------------------------------
# Selection
# ---------------------------------------------------------------------------
def select_mutations(mutations, count: int, seed: int):
    """Deterministically pick ``count`` mutations, balanced across categories.

    Categories are visited round-robin; within a category the order is a
    seeded shuffle.  The final list is sorted by mutation id so the output does
    not depend on dictionary iteration order.
    """
    by_category: dict[str, list] = {}
    for mutation in sorted(mutations, key=lambda item: item.id):
        by_category.setdefault(mutation.cat, []).append(mutation)
    categories = sorted(by_category)
    rng = random.Random(seed)
    for category in categories:
        rng.shuffle(by_category[category])

    picked: list = []
    round_index = 0
    while len(picked) < count:
        progressed = False
        for category in categories:
            if len(picked) >= count:
                break
            bucket = by_category[category]
            if round_index < len(bucket):
                picked.append(bucket[round_index])
                progressed = True
        if not progressed:
            break
        round_index += 1
    return sorted(picked, key=lambda item: item.id)


# ---------------------------------------------------------------------------
# Golden trace
# ---------------------------------------------------------------------------
def write_golden(out_dir, cycles: int) -> dict:
    assembled = core.assemble_text(GOLDEN_FIRMWARE)
    sim = core.simulate(assembled["programs"], cycles=cycles, capture_trace=True)
    rows = sim["trace"]
    if len(rows) != sim["cycles"]:  # pragma: no cover - internal consistency
        raise core.ProteusError("golden trace length does not match executed cycles")
    payload = "".join(core.json_line(row) for row in rows).encode()
    (out_dir / GOLDEN_TRACE_NAME).write_bytes(payload)
    digest = hashlib.sha256(payload).hexdigest()
    (out_dir / GOLDEN_SHA_NAME).write_text(f"{digest}  {GOLDEN_TRACE_NAME}\n")
    (out_dir / GOLDEN_FIRMWARE_NAME).write_text(GOLDEN_FIRMWARE)
    meta = {
        "cycles": cycles,
        "executed_cycles": sim["cycles"],
        "firmware": GOLDEN_FIRMWARE_NAME,
        "inputs": {"ui_in": 0, "uio_in": 0},
        "programs": {str(engine): words
                     for engine, words in sorted(assembled["programs"].items())},
        "schema": GOLDEN_SCHEMA,
        "sha256": digest,
        "trace_points": len(rows),
    }
    core.write_json(out_dir / GOLDEN_META_NAME, meta)
    return {"sha256": digest, "cycles": cycles, "trace_points": len(rows)}


# ---------------------------------------------------------------------------
# Task files
# ---------------------------------------------------------------------------
def write_tasks(out_dir, selected, golden_sha: str) -> list[dict]:
    mutate = core.load_tool("mutate")
    snapshot = mutate.snapshot()
    rows = []
    for mutation in selected:
        mutant_rel = f"{MUTANTS_DIR}/{mutation.id}/{mutation.file}"
        mutant_dir = out_dir / MUTANTS_DIR / mutation.id
        mutant_dir.mkdir(parents=True, exist_ok=True)
        line, reason = mutate.apply_mutation(mutant_dir, snapshot, mutation)
        if reason:
            raise core.ProteusError(f"mutation {mutation.id}: {reason}")
        line_text = snapshot[mutation.file].splitlines()[line - 1]
        mutant_path = out_dir / mutant_rel
        rows.append({
            "category": mutation.cat,
            "description": mutation.desc,
            "file": mutation.file,
            "find": mutation.find,
            "golden": GOLDEN_TRACE_NAME,
            "golden_sha256": golden_sha,
            "id": mutation.id,
            "line": line,
            "mutant": mutant_rel,
            "mutant_sha256": core.sha256_file(mutant_path),
            "original_line": line_text,
            "replace": mutation.repl,
            "schema": TASK_SCHEMA,
        })
    (out_dir / TASKS_NAME).write_text("".join(core.json_line(row) for row in rows))
    return rows


def write_readme(out_dir, rows: list[dict], *, seed: int, cycles: int) -> None:
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["category"]] = counts.get(row["category"], 0) + 1
    category_lines = "\n".join(
        f"| {category} | {counts[category]} |" for category in sorted(counts)
    )
    readme = f"""\
# PROTEUS agent debugging benchmark

{len(rows)} tasks generated from the `tools/mutate.py` catalogue, seed
{seed}, golden trace length {cycles} cycles.  Regenerate byte-identically:

```sh
python -m proteus bench --out DIR --seed {seed} --tasks {len(rows)} --cycles {cycles}
```

## Files

| path | contents |
|---|---|
| `{TASKS_NAME}` | one JSON object per task, sorted by mutation id |
| `{MUTANTS_DIR}/<id>/<file>` | the source file with exactly that mutation applied |
| `{GOLDEN_FIRMWARE_NAME}` | firmware used for the reference trace |
| `{GOLDEN_TRACE_NAME}` | one JSON object per executed cycle |
| `{GOLDEN_SHA_NAME}` | sha256 of `{GOLDEN_TRACE_NAME}` |
| `{GOLDEN_META_NAME}` | trace metadata, program words and inputs |

## Task fields

| field | meaning |
|---|---|
| `id` | mutation id from `tools/mutate.py` |
| `category` | mutation class (`alu`, `pacer`, `control`, ...) |
| `description` | the bug the mutation introduces |
| `file` | RTL file the mutation is in |
| `line` | 1-based line of the mutation in that file |
| `original_line` | the pristine source line |
| `find` / `replace` | the text substitution applied |
| `mutant` | mutated file, relative to this directory |
| `mutant_sha256` | sha256 of the mutated file |
| `golden` / `golden_sha256` | reference trace and its sha256 |

Category mix:

| category | tasks |
|---|---|
{category_lines}

## Golden trace

`{GOLDEN_TRACE_NAME}` is produced by `tools/model.py` (the executable
specification), not by the RTL.  Each row is:

```json
{{
  "cycle": 1,
  "engines": [{{"id": 0, "pc": 1, "halted": 0, "run": 1,
                "z": 0, "c": 0, "n": 0, "regs": [0, 0, 0, 0, 0, 0, 0, 0]}}],
  "pins": {{"uo_out": 0, "uio_out": 0, "uio_oe": 0,
            "uio_od": 0, "uio_drive": 0, "irq": 0}}
}}
```

Run the fixture yourself:

```sh
python -m proteus run {GOLDEN_FIRMWARE_NAME} --cycles {cycles} --trace
```

## Grading

The task supplies the mutant and its location; an agent should reproduce the
divergent behaviour, explain the mechanism, and patch the RTL.  The local
benches in `tools/mutate.py` already record which bench kills each mutation
(`results/mutation_root.md`); `python tools/mutate.py --only <ID>` re-runs one.

The golden trace is a model-level reference and says nothing about *where* in
the RTL a mutation lives.  To observe a mutant, compile the mutated file in
place of `src/<file>` with the repository's benches (`tb/run.sh`,
`tools/mutate.py`), not with `proteus run` -- `proteus run` only executes the
assembler and the golden model.
"""
    (out_dir / README_NAME).write_text(readme)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def _prepare_out_dir(path) -> None:
    if path.exists():
        if not path.is_dir():
            raise core.ProteusError(f"--out {path}: not a directory")
        unknown = sorted(
            entry.name for entry in path.iterdir() if entry.name not in MANAGED_ENTRIES
        )
        if unknown:
            raise core.ProteusError(
                f"--out {path}: contains unrelated entries: {', '.join(unknown)}"
            )
        shutil.rmtree(path / MUTANTS_DIR, ignore_errors=True)
    else:
        path.mkdir(parents=True)


def run(args) -> int:
    if args.tasks < 1:
        raise core.ProteusError(f"--tasks must be >= 1, got {args.tasks}")
    if args.cycles < 1:
        raise core.ProteusError(f"--cycles must be >= 1, got {args.cycles}")

    mutate = core.load_tool("mutate")
    snapshot = mutate.snapshot()
    usable = []
    for mutation in mutate.MUTATIONS:
        try:
            mutate.locate(snapshot, mutation)
        except ValueError as exc:
            raise core.ProteusError(
                f"mutation {mutation.id} does not apply to the current tree: {exc}"
            ) from exc
        usable.append(mutation)
    if args.tasks > len(usable):
        raise core.ProteusError(
            f"--tasks {args.tasks} exceeds the {len(usable)} applicable mutation specs"
        )

    out_dir = core.resolve_path(args.out)
    _prepare_out_dir(out_dir)

    golden = write_golden(out_dir, args.cycles)
    selected = select_mutations(usable, args.tasks, args.seed)
    rows = write_tasks(out_dir, selected, golden["sha256"])
    write_readme(out_dir, rows, seed=args.seed, cycles=args.cycles)

    print(f"out: {core.display_path(out_dir)}")
    print(f"tasks: {len(rows)}  seed: {args.seed}  golden cycles: {golden['cycles']}")
    print(f"trace: {golden['trace_points']} points  sha256: {golden['sha256']}")
    print("ids: " + " ".join(row["id"] for row in rows))
    return 0
